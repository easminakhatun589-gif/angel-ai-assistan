package com.jarvis.assistant.ui.preview

import android.annotation.SuppressLint
import android.content.ClipData
import android.content.ClipboardManager
import android.content.Context
import android.content.Intent
import android.graphics.BitmapFactory
import android.os.Bundle
import android.view.View
import android.webkit.WebChromeClient
import android.webkit.WebSettings
import android.webkit.WebView
import android.webkit.WebViewClient
import android.widget.Toast
import androidx.appcompat.app.AppCompatActivity
import com.jarvis.assistant.databinding.ActivityLivePreviewBinding
import java.io.File

class LivePreviewActivity : AppCompatActivity() {

    companion object {
        const val EXTRA_MODE = "mode" // "CODE", "PHOTO", "VIDEO"
        const val EXTRA_TITLE = "title"
        const val EXTRA_PROVIDER = "provider"
        const val EXTRA_PROMPT = "prompt"
        const val EXTRA_HTML = "html"
        const val EXTRA_FILE_PATH = "file_path"

        fun startCode(context: Context, title: String, provider: String, prompt: String, html: String) {
            val intent = Intent(context, LivePreviewActivity::class.java).apply {
                putExtra(EXTRA_MODE, "CODE")
                putExtra(EXTRA_TITLE, title)
                putExtra(EXTRA_PROVIDER, provider)
                putExtra(EXTRA_PROMPT, prompt)
                putExtra(EXTRA_HTML, html)
                flags = Intent.FLAG_ACTIVITY_NEW_TASK
            }
            context.startActivity(intent)
        }

        fun startPhoto(context: Context, title: String, provider: String, prompt: String, filePath: String) {
            val intent = Intent(context, LivePreviewActivity::class.java).apply {
                putExtra(EXTRA_MODE, "PHOTO")
                putExtra(EXTRA_TITLE, title)
                putExtra(EXTRA_PROVIDER, provider)
                putExtra(EXTRA_PROMPT, prompt)
                putExtra(EXTRA_FILE_PATH, filePath)
                flags = Intent.FLAG_ACTIVITY_NEW_TASK
            }
            context.startActivity(intent)
        }

        fun startVideo(context: Context, title: String, provider: String, prompt: String, html: String) {
            val intent = Intent(context, LivePreviewActivity::class.java).apply {
                putExtra(EXTRA_MODE, "VIDEO")
                putExtra(EXTRA_TITLE, title)
                putExtra(EXTRA_PROVIDER, provider)
                putExtra(EXTRA_PROMPT, prompt)
                putExtra(EXTRA_HTML, html)
                flags = Intent.FLAG_ACTIVITY_NEW_TASK
            }
            context.startActivity(intent)
        }
    }

    private lateinit var binding: ActivityLivePreviewBinding
    private var currentMode = "CODE"
    private var currentHtml = ""

    @SuppressLint("SetJavaScriptEnabled")
    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        binding = ActivityLivePreviewBinding.inflate(layoutInflater)
        setContentView(binding.root)

        currentMode = intent.getStringExtra(EXTRA_MODE) ?: "CODE"
        val title = intent.getStringExtra(EXTRA_TITLE) ?: "JARVIS AI Output"
        val provider = intent.getStringExtra(EXTRA_PROVIDER) ?: "DeepSeek AI"
        val prompt = intent.getStringExtra(EXTRA_PROMPT) ?: ""
        currentHtml = intent.getStringExtra(EXTRA_HTML) ?: ""
        val filePath = intent.getStringExtra(EXTRA_FILE_PATH) ?: ""

        binding.tvProjectTitle.text = title
        binding.tvProviderBadge.text = "Generated by $provider"

        setupWebView()

        when (currentMode) {
            "PHOTO" -> {
                binding.layoutTabs.visibility = View.GONE
                binding.webViewLive.visibility = View.GONE
                binding.scrollCodeView.visibility = View.GONE
                binding.btnCopyCode.visibility = View.GONE
                binding.btnReload.visibility = View.GONE
                binding.layoutPhotoView.visibility = View.VISIBLE

                binding.tvPhotoPrompt.text = "\"$prompt\""
                if (filePath.isNotBlank()) {
                    val file = File(filePath)
                    if (file.exists()) {
                        val bmp = BitmapFactory.decodeFile(file.absolutePath)
                        binding.ivGeneratedPhoto.setImageBitmap(bmp)
                    }
                }
            }
            "VIDEO" -> {
                binding.layoutTabs.visibility = View.GONE
                binding.scrollCodeView.visibility = View.GONE
                binding.layoutPhotoView.visibility = View.GONE
                binding.btnCopyCode.visibility = View.GONE
                binding.webViewLive.visibility = View.VISIBLE

                loadHtml(currentHtml)
            }
            else -> { // "CODE"
                binding.layoutPhotoView.visibility = View.GONE
                binding.layoutTabs.visibility = View.VISIBLE
                binding.webViewLive.visibility = View.VISIBLE
                binding.scrollCodeView.visibility = View.GONE

                binding.tvCodeDisplay.text = currentHtml
                loadHtml(currentHtml)
            }
        }

        setupListeners()
    }

    @SuppressLint("SetJavaScriptEnabled")
    private fun setupWebView() {
        val webView = binding.webViewLive
        webView.settings.apply {
            javaScriptEnabled = true
            domStorageEnabled = true
            databaseEnabled = true
            useWideViewPort = true
            loadWithOverviewMode = true
            mediaPlaybackRequiresUserGesture = false
            mixedContentMode = WebSettings.MIXED_CONTENT_ALWAYS_ALLOW
        }
        webView.webChromeClient = WebChromeClient()
        webView.webViewClient = object : WebViewClient() {}
    }

    private fun loadHtml(html: String) {
        binding.webViewLive.loadDataWithBaseURL("https://jarvis.ai/", html, "text/html", "UTF-8", null)
    }

    private fun setupListeners() {
        binding.btnClose.setOnClickListener {
            finish()
        }

        binding.btnReload.setOnClickListener {
            if (currentMode == "CODE" || currentMode == "VIDEO") {
                loadHtml(currentHtml)
                Toast.makeText(this, "Reloading project...", Toast.LENGTH_SHORT).show()
            }
        }

        binding.btnCopyCode.setOnClickListener {
            val clip = getSystemService(Context.CLIPBOARD_SERVICE) as ClipboardManager
            clip.setPrimaryClip(ClipData.newPlainText("JARVIS Code", currentHtml))
            Toast.makeText(this, "Complete Real Code copied to clipboard!", Toast.LENGTH_SHORT).show()
        }

        binding.tabLivePreview.setOnClickListener {
            binding.tabLivePreview.setTextColor(android.graphics.Color.parseColor("#00E5FF"))
            binding.tabSourceCode.setTextColor(android.graphics.Color.parseColor("#94A3B8"))
            binding.webViewLive.visibility = View.VISIBLE
            binding.scrollCodeView.visibility = View.GONE
        }

        binding.tabSourceCode.setOnClickListener {
            binding.tabSourceCode.setTextColor(android.graphics.Color.parseColor("#00E5FF"))
            binding.tabLivePreview.setTextColor(android.graphics.Color.parseColor("#94A3B8"))
            binding.webViewLive.visibility = View.GONE
            binding.scrollCodeView.visibility = View.VISIBLE
        }

        binding.btnSavePhoto.setOnClickListener {
            Toast.makeText(this, "Photo saved to device cache and gallery!", Toast.LENGTH_SHORT).show()
        }

        binding.btnSharePhoto.setOnClickListener {
            val shareIntent = Intent(Intent.ACTION_SEND).apply {
                type = "text/plain"
                putExtra(Intent.EXTRA_TEXT, "Generated with JARVIS AI: ${binding.tvPhotoPrompt.text}")
            }
            startActivity(Intent.createChooser(shareIntent, "Share AI Photo"))
        }
    }

    override fun onDestroy() {
        binding.webViewLive.destroy()
        super.onDestroy()
    }
}
